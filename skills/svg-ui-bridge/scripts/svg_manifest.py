#!/usr/bin/env python3
"""Decompose a design SVG into a component manifest the agent implements from.

Writes <name>.components.json (machine-readable) and <name>.components.md (for the spec/plan).
Each component gets: id, parent, depth, bounding box (measured by rendering it in isolation),
data-layout, tokens it uses, its data-state variants, text content and any data-note.

  python svg_manifest.py design/settings.svg
  python svg_manifest.py design/settings.svg --no-bbox      # skip rendering (fast)
"""
from __future__ import annotations

import argparse
import json
import re
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _svgcommon import canvas_size, components, isolate, load_svg, local, render_svg_bytes, show_state  # noqa: E402
import xml.etree.ElementTree as ET  # noqa: E402

VAR = re.compile(r"var\(--([\w-]+)")
TOKEN_DEF = re.compile(r"--([\w-]+)\s*:\s*([^;]+);")


def tokens_defined(root) -> dict[str, str]:
    css = "".join((s.text or "") for s in root.iter() if local(s.tag) == "style")
    return {k: v.strip() for k, v in TOKEN_DEF.findall(css)}


def own_iter(el):
    """Iterate el and its descendants, but not into nested components (they get their own row)."""
    yield el
    for c in el:
        if local(c.tag) == "g" and c.get("data-component") is not None:
            continue
        yield from own_iter(c)


def tokens_used(el) -> list[str]:
    found = set()
    for e in own_iter(el):
        for k, v in e.attrib.items():
            found.update(VAR.findall(v))
            if k == "data-token":
                found.update(t.strip() for t in v.split(","))
    return sorted(found)


def own_text(el) -> list[str]:
    out = []
    for e in own_iter(el):
        if local(e.tag) in ("text", "tspan") and e.text and e.text.strip():
            out.append(e.text.strip())
    return out


def bbox_of(tree, cid: str, scale: float, td: str):
    from PIL import Image
    png = Path(td) / f"{cid}.png"
    data = isolate(ET.ElementTree(ET.fromstring(show_state(tree, None))), cid)
    render_svg_bytes(data, png, scale=scale, size=canvas_size(tree.getroot()))
    im = Image.open(png).convert("RGBA")
    box = im.getchannel("A").getbbox()
    if not box:
        return None
    x0, y0, x1, y1 = (v / scale for v in box)
    return [round(x0, 1), round(y0, 1), round(x1 - x0, 1), round(y1 - y0, 1)]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("svg")
    ap.add_argument("--no-bbox", action="store_true")
    ap.add_argument("--scale", type=float, default=1.0)
    a = ap.parse_args()

    src = Path(a.svg)
    tree = load_svg(src)
    root = tree.getroot()
    w, h = canvas_size(root)
    screen = root.get("data-screen") or src.stem
    defined = tokens_defined(root)

    comps = []
    with tempfile.TemporaryDirectory() as td:
        for el, depth, parent in components(root):
            cid = el.get("id")
            if not cid:
                continue
            states = sorted({s.get("data-state") for s in own_iter(el) if s.get("data-state")})
            comps.append({
                "id": cid,
                "kind": el.get("data-component") or "",
                "parent": parent,
                "depth": depth,
                "bbox": None if a.no_bbox else bbox_of(tree, cid, a.scale, td),
                "layout": el.get("data-layout") or "",
                "tokens": tokens_used(el),
                "states": states,
                "text": own_text(el)[:8],
                "note": el.get("data-note") or "",
            })

    used_all = sorted({t for e in root.iter() for t in tokens_used(e)})
    undefined = [t for t in used_all if t not in defined and "." not in t]
    manifest = {"screen": screen, "source": src.name, "canvas": [w, h],
                "tokens": defined, "undefined_tokens": undefined, "components": comps}

    jpath = src.with_suffix(".components.json")
    jpath.write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8")

    lines = [f"# {screen} — component manifest", "",
             f"Source: `{src.name}` · canvas {w:g}×{h:g} · {len(comps)} components", "",
             "Generated by svg_manifest.py. Implement one component per plan task, leaves first.", "",
             "## Tokens", ""]
    if defined:
        lines += ["| token | value |", "|---|---|"] + [f"| `--{k}` | `{v}` |" for k, v in defined.items()]
    else:
        lines.append("_No CSS-variable tokens defined in the SVG._")
    if undefined:
        lines += ["", f"⚠ used but not defined: {', '.join('--'+u for u in undefined)}"]
    lines += ["", "## Components (tree order)", "",
              "| component | kind | bbox x,y,w,h | layout | states | tokens | notes |",
              "|---|---|---|---|---|---|---|"]
    for c in comps:
        name = "&nbsp;&nbsp;" * c["depth"] + ("└ " if c["depth"] else "") + f"`{c['id']}`"
        bb = ",".join(f"{v:g}" for v in c["bbox"]) if c["bbox"] else "—"
        txt = (" · text: " + " / ".join(c["text"])) if c["text"] else ""
        lines.append(f"| {name} | {c['kind']} | {bb} | {c['layout'] or '—'} | {', '.join(c['states']) or '—'} "
                     f"| {', '.join(c['tokens']) or '—'} | {c['note']}{txt} |")
    lines += ["", "## Suggested build order (leaves first)", ""]
    order = sorted(comps, key=lambda c: -c["depth"])
    for i, c in enumerate(order, 1):
        lines.append(f"{i}. `{c['id']}`" + (f" (inside `{c['parent']}`)" if c["parent"] else ""))
    mpath = src.with_suffix(".components.md")
    mpath.write_text("\n".join(lines) + "\n", encoding="utf-8")

    print(f"wrote {jpath} and {mpath}: {len(comps)} components, {len(defined)} tokens"
          + (f", {len(undefined)} undefined token(s)" if undefined else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
