#!/usr/bin/env python3
"""Generate the code-side token/theme file from the SVG's CSS-variable tokens (do this once,
then re-run whenever the SVG tokens change — never hand-copy colours).

  python tokens_export.py design/app.svg --format css   -o src/styles/tokens.css
  python tokens_export.py design/app.svg --format ts    -o src/theme/tokens.ts
  python tokens_export.py design/app.svg --format egui  -o src/theme.rs
  python tokens_export.py design/app.svg --format bevy  -o src/ui_theme.rs
  python tokens_export.py design/app.svg --format json
  python tokens_export.py design/html/review.html --format ts    # HTML draft: its local CSS variables
  python tokens_export.py design/html/theme.css --format egui
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _htmldraft import css_tokens, is_html  # noqa: E402
from _svgcommon import load_svg, local  # noqa: E402

DEF = re.compile(r"--([\w-]+)\s*:\s*([^;}]+)[;}]")
HEX = re.compile(r"^#([0-9a-fA-F]{3}|[0-9a-fA-F]{6}|[0-9a-fA-F]{8})$")


def tokens(svg: Path) -> dict[str, str]:
    if svg.suffix.lower() == ".css" or is_html(svg):
        return css_tokens(svg)
    root = load_svg(svg).getroot()
    css = "".join((s.text or "") for s in root.iter() if local(s.tag) == "style")
    return {k: v.strip() for k, v in DEF.findall(css)}


def rgba(hexv: str):
    h = HEX.match(hexv).group(1)
    if len(h) == 3:
        h = "".join(c * 2 for c in h)
    r, g, b = (int(h[i:i + 2], 16) for i in (0, 2, 4))
    a = int(h[6:8], 16) if len(h) == 8 else 255
    return r, g, b, a


def ident(name: str, style: str) -> str:
    parts = re.split(r"[-_.]", name)
    if style == "SCREAMING":
        return "_".join(p.upper() for p in parts)
    if style == "camel":
        return parts[0] + "".join(p.capitalize() for p in parts[1:])
    return "_".join(parts)


def render(toks: dict[str, str], fmt: str, src: str) -> str:
    head = f"generated by tokens_export.py from {src} — edit the tokens there, not this file"
    if fmt == "css":
        return f"/* {head} */\n:root {{\n" + "".join(f"  --{k}: {v};\n" for k, v in toks.items()) + "}\n"
    if fmt == "json":
        return json.dumps(toks, indent=2) + "\n"
    if fmt == "ts":
        body = "".join(f"  {ident(k, 'camel')}: {json.dumps(v)},\n" for k, v in toks.items())
        return f"// {head}\nexport const tokens = {{\n{body}}} as const;\n"
    if fmt in ("egui", "bevy"):
        lines = [f"// {head}"]
        if fmt == "egui":
            lines.append("use egui::Color32;\n")
        else:
            lines.append("use bevy::prelude::Color;\n")
        for k, v in toks.items():
            n = ident(k, "SCREAMING")
            if HEX.match(v):
                r, g, b, a = rgba(v)
                if fmt == "egui":
                    lines.append(f"pub const {n}: Color32 = Color32::from_rgba_unmultiplied({r}, {g}, {b}, {a});")
                else:
                    lines.append(f"pub const {n}: Color = Color::srgba_u8({r}, {g}, {b}, {a});")
            elif re.fullmatch(r"-?[\d.]+px", v):
                lines.append(f"pub const {n}: f32 = {float(v[:-2])};")
            else:
                lines.append(f"// {n}: {v}  (not a colour or px value — map by hand)")
        return "\n".join(lines) + "\n"
    raise SystemExit(f"unknown format {fmt}")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("svg")
    ap.add_argument("--format", default="css", choices=["css", "json", "ts", "egui", "bevy"])
    ap.add_argument("-o", "--out")
    a = ap.parse_args()
    toks = tokens(Path(a.svg))
    if not toks:
        print("no --tokens found in the SVG <style>", file=sys.stderr)
        return 1
    text = render(toks, a.format, Path(a.svg).name)
    if a.out:
        Path(a.out).parent.mkdir(parents=True, exist_ok=True)
        Path(a.out).write_text(text, encoding="utf-8")
        print(f"wrote {a.out} ({len(toks)} tokens)")
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
